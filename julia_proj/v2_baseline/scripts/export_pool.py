"""Export the Python V2 scenario pool to a deterministic text file for Julia.

Why: NumPy's ``default_rng`` stream cannot be reproduced bit-for-bit by Julia's
RNG.  The Julia model must use the *same* 300 (z, Theta) scenes as the Python
V2 baseline, so the authoritative pool is generated here and loaded by Julia.

The exporter only reads the Python project (config/problem.toml and
code/problem_data.py).  It writes new files under ``v2_baseline/data/`` and
never modifies Python code or results.

Usage (from anywhere):
    python julia_proj/v2_baseline/scripts/export_pool.py
    python .../export_pool.py --config path/to/problem.toml --out pool.txt

File format (one scene per line):
    line 1:  <pool_size> <N_R> <G> <T> <seed>
    line s:  115 floats separated by spaces
             - first 3*N_R values: z in NumPy C order, shape (3, N_R)
             - next N_R*G*(G+1) values: Theta in NumPy C order,
               shape (N_R, G, G+1)

The companion ``*_meta.toml`` stores first-scene values, pooled means and
P_ref so the Julia loader can be checked against the exact Python draws.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np

# v2_baseline/scripts/export_pool.py -> parents[3] is the Python project root.
ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT))

from code.config import load_problem_config          # noqa: E402
from code.problem_data import DefineProblem, _cov_factor  # noqa: E402

DEFAULT_CONFIG = ROOT / "config" / "problem.toml"
DEFAULT_DATA_DIR = Path(__file__).resolve().parents[1] / "data"


def _fmt(vals) -> str:
    """TOML array (commas are required; the pool file uses spaces separately)."""
    return ", ".join(f"{float(v):.17g}" for v in np.asarray(vals, dtype=float).ravel(order="C"))


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--config", default=str(DEFAULT_CONFIG))
    ap.add_argument("--out", default=None,
                    help="pool file; default data/pool_seed<seed>.txt")
    args = ap.parse_args()

    cfg_path = Path(args.config).resolve()
    cfg = load_problem_config(cfg_path)
    prob = DefineProblem(cfg)

    out = Path(args.out) if args.out else (
        DEFAULT_DATA_DIR / f"pool_seed{prob.seed}.txt")
    out.parent.mkdir(parents=True, exist_ok=True)
    meta = out.with_name(out.stem + "_meta.toml")

    n_vals = 3 * prob.N_R + prob.N_R * prob.G * (prob.G + 1)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(f"{len(prob.pool)} {prob.N_R} {prob.G} {prob.T} {prob.seed}\n")
        for z, th in prob.pool:
            vals = np.concatenate([z.ravel(order="C"),
                                   th.ravel(order="C")])
            assert vals.size == n_vals
            f.write(" ".join(f"{float(v):.17g}" for v in vals) + "\n")

    z0, th0 = prob.pool[0]
    th_bar = np.mean([th for _, th in prob.pool], axis=0)
    f_pool = np.mean([
        _cov_factor(prob.beta_cov, prob.z_bar, z[:, r])
        for z, _ in prob.pool for r in range(prob.N_R)
    ])

    with open(meta, "w", encoding="utf-8", newline="\n") as f:
        f.write("# Generated by scripts/export_pool.py; do not edit.\n")
        f.write(f"pool_size = {len(prob.pool)}\n")
        f.write(f"N_R = {prob.N_R}\nG = {prob.G}\nT = {prob.T}\nseed = {prob.seed}\n")
        f.write(f"state_dim = {prob.state_dim}\n")
        f.write(f"first_z = [{_fmt(z0)}]\n")
        f.write(f"first_theta = [{_fmt(th0)}]\n")
        f.write(f"mean_theta = [{_fmt(th_bar)}]\n")
        f.write(f"pool_mean_f = {f_pool:.17g}\n")
        f.write(f"P_ref = [{_fmt(prob.P_ref)}]\n")

    print(f"config     : {cfg_path}")
    print(f"pool written: {out}  ({len(prob.pool)} scenes, {n_vals} values/scene)")
    print(f"meta written: {meta}")
    print(f"seed={prob.seed}  N_R={prob.N_R}  G={prob.G}  T={prob.T}  "
          f"state_dim={prob.state_dim}  pool_mean_f={f_pool:.6f}")


if __name__ == "__main__":
    main()
